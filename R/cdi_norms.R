# Meant to work with SEEDLingS CDI spreadsheet, but potentially useful for other CDI that lacks norms.

#'Load in the correct norm table based on gender and metric. The norm conversion table was downloaded from [wordbank](https://github.com/langcog/wordbank-shiny/tree/main/apps/scoring/norms/percentiles/English%20Percentiles)
#'
get_norm_path <- function(form, gender, metric) {
  if (form == "WG") {
    if (metric == "comp") {
      norm_path <- file.path(form, paste0(form, "comp_", gender, "_nohighcomp_1.csv"))
    } else {
      norm_path <- file.path(form, paste0(form, metric, "_", gender, "_1.csv"))
    }
  } else {
    norm_path <- file.path(form, paste0(form, metric, "_", gender, "_36_1.csv"))
  }
  
  norm_path <- system.file("extdata", norm_path, package = "blabr")
  return(norm_path)
}

#'Wrangling norm conversion tables into one row for each percentile (1-99) for each age
#'
wrangle_norm <- function(form, gender, metric) {
  norm_path <- get_norm_path(form, gender, metric)
  df_raw <- readr::read_csv(norm_path, skip = 1, show_col_types = FALSE)
  norm_df <- df_raw %>% 
    dplyr::rename(percentile = age) %>%
    tidyr::pivot_longer(cols = -percentile, names_to = "age", values_to = metric, names_transform = as.integer) %>% 
    dplyr::mutate(form = form, gender = gender) %>%
    dplyr::select(form, gender, everything())
  
  return(norm_df)
}

#'Load CDI norms for all metrics and all genders for WG form
#'
#'@return A list of three dataframes ("boys", "girls", "both"). Each dataframe is 
#'a combined norm conversion table for every WG metrics for that gender. Each row 
#'is one percentile (1-99) for each age (8-18), each column is a different metric
#'(e.g. comp, prod, earlygest,...), and each cell is the score for that metric at 
#'said percentile
#'
#'@export  
load_cdi_norms_wg <- function() {
  all_norm_path <- system.file("extdata", "cdi_norms_wg.rds", package = "blabr")
  if (file.exists(all_norm_path)) {
    message(paste0("Loading cached CDI norms from ", all_norm_path))
    all_norms <- readRDS(all_norm_path)
    return(all_norms)
  }
  
  metrics_wg <- c("phrases", "comp", "prod", "earlygest", "lategest", "totgest")
  # metrics_ws <- c("prod", "wordforms", "wordend2", "M3L", "complex")
  
  genders <- c("girls", "boys", "both")
  
  all_norms <- list()
  
  for (gender in genders) {
    norm_by_gender <- data.frame()
    for (metric in metrics_wg) {
      wrangled = wrangle_norm("WG", gender, metric)
      if (nrow(norm_by_gender) == 0) {
        norm_by_gender <- wrangled
      } else {
        norm_by_gender <- dplyr::full_join(norm_by_gender, wrangled, by = c("form", "gender", "percentile", "age"))
      }
    }
    all_norms[[gender]] <- norm_by_gender
  }
  
  return(all_norms)
}

#'Calculate percentile scores for each metric in SEEDLingS CDI spreadsheet and 
#'add them as new column.
#'
#'@details 
#'This function will modify the existing spreadsheet by adding a new column named, say `CDIcomp-percentile-both` (if `both=TRUE`) or `CDIcomp-percentile-sex` (if `both=FALSE`), if called on col `CDIcomp`. For each `CDIcomp` score, if will first match the age and find the closest score less than or equal to the child's score, and return the highest percentile that score matched to. The new column will be next to their original score column
#'
#'@param df SEEDLingS CDI spreadsheet as retrieved by `get_seedlings_cdi()`
#'@param norms Norm conversion table to use, as generated by `load_cdi_norms_wg()`
#'@param col String indicating which metric (i.e. which column) to convert to percentile score
#'@param both A boolean value, Indicating whether we're calculating percentile score 
#'by sex or for both sexes. 
#'
#'@export
#'
calculate_percentile <- function(df, norms, col, both) {
  if (both) {
    new_col_name <- paste(col, "percentile", "both", sep = "-")
  } else {
    new_col_name <- paste(col, "percentile", "sex", sep = "-")
  }
  
  norms <- norms %>% 
    dplyr::select(age, score = all_of(col), percentile) %>% 
    dplyr::group_by(age, score) %>% 
    dplyr::slice_max(percentile, n = 1) %>% # Only select the highest percentile for each score
    dplyr::arrange(age, score)
  
  df %>% 
    dplyr::mutate(.x = .data[[col]]) %>% 
    dplyr::left_join(
      norms, 
      by = dplyr::join_by(month == age, closest(.x >= score))
    ) %>% # Join with norm table my matching age, and then selecting for the percentile with the closest score that's less than or equal to the child's score
    dplyr::select(-.x, -score) %>% 
    dplyr::relocate(percentile, .after = col) %>% 
    dplyr::rename(!!new_col_name := percentile)  # because new_col_name is a string, we have to "dequote" with `!!` and then assigned with ":="

}

#'Adding percentile scores to existing SEEDLingS CDI spreadsheet
#'
#'@details
#'Iteratively go through every summary metrics (if any) in SEEDLingS CDI summary table and calculate the percentile score, by sex and for both sexes, adding two new columns for each metric. E.g., for `CDIcomp`, the two new columns added are `CDIcomp-percentile-both` and `CDIcomp-percentile-sex`. Return a new dataframe with all these new columns. The new columns will be next to their original score column
#'
#'@param cdi_df SEEDLingS CDI spreadsheet as retrieved by `get_seedlings_cdi()`
#'
#'@export
add_norms_to_cdi <- function(cdi_df) {
  all_norms <- load_cdi_norms_wg()
  col_to_filename_key <- data.frame(
    metric = c("phrases", "comp", "prod", "earlygest", "lategest", "totgest"),
    col_name = c("phrases", "CDIcomp", "CDIprod", "early_gestures", "later_gestures", "total_gestures")
  ) # Because the names in the norm table is different from seedlings colnames
  name_mapping <- setNames(col_to_filename_key$metric, col_to_filename_key$col_name)
  
  norm_both <- all_norms[["both"]] %>% 
    dplyr::rename(any_of(name_mapping)) # rename the norms table's colnames to match SEEDLingS CDI spreadsheet
  
  cdi_with_percentile <- data.frame()
  
  for (gender in c("boys", "girls")) {
    if (gender == "girls") {
      cdi_df_by_gender <- cdi_df %>% 
        dplyr::filter(Child_gender == "Female") 
    } else {
      cdi_df_by_gender <- cdi_df %>% 
        dplyr::filter(Child_gender == "Male") 
    }
    norm_by_gender <- all_norms[[gender]] %>% 
      dplyr::rename(any_of(name_mapping)) # rename the norms table's colnames to match SEEDLingS CDI spreadsheet
    
    cdi_df_with_percentile_by_gender <- purrr::reduce(
      col_to_filename_key$col_name, 
      \(d, col) calculate_percentile(d, norm_by_gender, col, FALSE), 
      .init = cdi_df_by_gender
    ) # iteratively applying `calculate_percentile()` to each summary column, and adding new percentile scores
    
    cdi_df_with_percentile_both <- purrr::reduce(
      col_to_filename_key$col_name, 
      \(d, col) calculate_percentile(d, norm_both, col, TRUE), 
      .init = cdi_df_with_percentile_by_gender
    ) # Similarly, but for percentile score across both sexes
    cdi_with_percentile <- dplyr::bind_rows(cdi_with_percentile, cdi_df_with_percentile_both) # Combining the results for girls and boys
  }
  
  return(cdi_with_percentile %>% dplyr::arrange(SubjectNumber))
}